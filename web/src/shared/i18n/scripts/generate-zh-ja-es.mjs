function writeLocale(code, dict) {
  const out = {}
  const keys = Object.keys(en).sort()
  for (const k of keys) {
    if (!(k in dict)) {
      throw new Error(`Missing ${code} translation for key: ${k}`)
    }
    out[k] = dict[k]
  }
  fs.writeFileSync(
    path.join(localesDir, `${code}.json`),
    `${JSON.stringify(out, null, 2)}\n`,
  )
}

